                # Duas formas de conexão criptografada com o Gmail:
                #   TLS na porta 587 (padrão)  |  SSL na porta 465 (GMAIL_USAR_SSL=True no .env)
                # Se der "Connection unexpectedly closed", use SSL: antivírus e algumas
                # redes bloqueiam ou interferem na porta 587.
